#import "import.h"

#import <string.h>


static BOOL   drawStuff( CALayer *layer, CGContext *context)
{
   struct NVGcontext   *vg;
   CGFloat             deg;
   CAPolarPoint        pPoint;
   CGPoint             point;
   CGRect              canvas;
   NSUInteger          circles;
   CGFloat             hue;
   NSUInteger          numberOfFrames;

   canvas = [layer canvas];

   vg             = CGContextGetNVGContext( context);
   numberOfFrames = [context numberOfFrames];

   nvgSave( vg);
   {
      nvgTranslate( vg, canvas.size.width / 2.0, canvas.size.height / 2.0);
      for( circles = 0; circles < 5; circles++)
      {
         for( deg = 0; deg < 360.0; deg += 2.0)
         {
            pPoint = CAPolarPointMakeWithAngle( canvas.size.height / 2.0 - (circles + 1) * 10.0,
                                                CADegreesToAngle( deg));
            point  = CGPointMakeWithPolarPoint( pPoint);

            nvgBeginPath( vg);
            nvgCircle( vg, point.x, point.y, 3.0);
            hue = CADegreesToRotation( (circles * 90.0) + deg + (numberOfFrames * (circles + 1) / 0.4));
            hue = fmodf( hue, 1.0f);
            nvgFillColor( vg, CGColorMakeWithHSL( hue, 1.0, 0.5));
            nvgFill( vg);
         }
      }
   }
   nvgRestore( vg);

   return( YES);
}


void   setupScene( UIWindowPlane *contentPlane)
{
   UIView        *view;
   CGRect         frame;
   UIEdgeInsets   insets;
   CALayer        *layer;

   frame  = [contentPlane frame];
   insets = UIEdgeInsetsMake( 8, 8, 8, 8);
   frame  = UIEdgeInsetsInsetRect( frame, insets);

   view  = [UIView viewWithFrame:frame];
   layer = [view layer];
   [layer setDrawCallback:drawStuff];
   [contentPlane addSubview:view];
}


int   main()
{
   UIWindow        *window;
   UIApplication   *app;

   /*
    * window and app
    */
   app = [UIApplication sharedInstance];
   @autoreleasepool
   {
      window = [UIWindow windowWithFrame:CGRectMake( 0.0, 0.0, 800.0, 600.0)];

      [app addWindow:window];

      [window setBackgroundColor:CGColorMakeWithRGBA( 0.0, 0.0, 0.0, 1.0)];
      [window setFrameRateHz:60.0];

      setupScene( [window contentPlane]);
   }
   return( [app run]);
}




