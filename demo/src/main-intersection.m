#import "import.h"


static void  drawDot( CGContext *context, CGPoint p, CGColor color)
{
   struct NVGcontext   *vg;

   vg = CGContextGetNVGContext( context);

   nvgBeginPath( vg);
   nvgCircle( vg, p.x, p.y, 3.0);
   nvgFillColor( vg, color);
   nvgFill( vg);
}


static BOOL   drawStuff( CALayer *layer, CGContext *context)
{
   struct NVGcontext   *vg;
   CGRect              canvas;
   CGRect              rect;
   CACircle            bigCircle;
   CACircle            smallCircle;
   CAAngle             angle;
   CGFloat             hue;
   CGFloat             deg;
   CAPolarPoint        q0;
   CGPoint             p1;
   CGPoint             p2;
   CGColor             color;
   NSUInteger          numberOfFrames;
   CGFloat             factor;

   vg     = CGContextGetNVGContext( context);
   canvas = [layer canvas];
   rect   = CGRectInset( canvas, 50, 50);

   bigCircle = CGRectGetInnerCircle( rect);

   mvgStrokeCircleWithColor( vg, bigCircle, 1.0, CGColorMakeGray());

   numberOfFrames = [context numberOfFrames] % 480;

   for( deg = 0; deg < 360.0; deg += 5.0)
   {
      hue   = CADegreesToRotation( deg);
      hue   = fmodf( hue, 1.0f);
      color = CGColorMakeWithHSL( hue, 1.0, 0.5);

      factor = (numberOfFrames / 480.0);
      angle  = CADegreesToAngle( deg * factor);
      q0     = CAPolarPointMakeWithAngle( bigCircle.radius, angle);

      smallCircle.center = CGPointAdd( CGPointMakeWithPolarPoint( q0), bigCircle.center);
      smallCircle.radius = 1.0 + factor * deg * (bigCircle.radius / 180.0);

      mvgStrokeCircleWithColor( vg, smallCircle, 1.0, color);

//      if( CACircleIntersectionsWithCircle( bigCircle, smallCircle, intersection))
//      {
//         drawDot( context, intersection[ 0], CGColorMakeRed());
//         drawDot( context, intersection[ 1], CGColorMakeGreen());
//      }

      p1 = CACirclePointAtDistance( bigCircle, angle, smallCircle.radius);
      if( ! CGPointIsNull( p1))
         drawDot( context, p1, CGColorMakeRed());
      p2 = CACirclePointAtDistance( bigCircle, angle, -smallCircle.radius);
      if( ! CGPointIsNull( p2))
         drawDot( context, p2, CGColorMakeLime());
   }

   return( YES);
}


int   main( int argc, char *argv[])
{
   return( UIApplicationRunDrawCallbackHz( (CALayerDrawCallback_t *) drawStuff,
                                           CGSizeMake( 800, 800),
                                           NULL,
                                           60.0f));
}




